import { NextResponse } from 'next/server';
import { z } from 'zod';
import { getSchoolContext, hasModulePermission } from '@/lib/auth/school-context';
import { createSupabaseAdminClient, createSupabaseServerClient } from '@/lib/supabase/server';
import {
  getMonthDateRange,
  getTeacherAttendanceMapForMonth,
  syncMonthlySalarySlipsForSchool,
} from '@/lib/payroll/auto-salary';
import { ensurePublicUserProfile } from '@/lib/auth/ensure-user-profile';

const PostActionSchema = z.discriminatedUnion('action', [
  z.object({
    action: z.literal('generate_month'),
    payroll_month: z.string().regex(/^\d{4}-\d{2}$/),
  }),
  z.object({
    action: z.literal('save_adjustment'),
    teacher_id: z.string().uuid(),
    payroll_month: z.string().regex(/^\d{4}-\d{2}$/),
    allowances: z.coerce.number().min(0).default(0),
    bonuses: z.coerce.number().min(0).default(0),
    deductions: z.coerce.number().min(0).default(0),
    advance_salary: z.coerce.number().min(0).default(0),
  }),
]);

const PatchActionSchema = z.discriminatedUnion('action', [
  z.object({
    action: z.literal('mark_paid'),
    slip_id: z.string().uuid(),
    payment_method: z.string().trim().min(2).default('Cash'),
  }),
  z.object({
    action: z.literal('mark_unpaid'),
    slip_id: z.string().uuid(),
  }),
  z.object({
    action: z.literal('pay_all_unpaid'),
    payroll_month: z.string().regex(/^\d{4}-\d{2}$/),
    payment_method: z.string().trim().min(2).default('Bank Transfer'),
  }),
]);

export async function GET(request: Request) {
  const authResult = await getSchoolContext();
  if (authResult.status !== 'ok') {
    return NextResponse.json({ error: 'Unauthorized or unapproved school.' }, { status: 403 });
  }

  const { context } = authResult;
  if (!hasModulePermission(context.member, 'payroll')) {
    return NextResponse.json({ error: 'Insufficient module permissions for Payroll.' }, { status: 403 });
  }

  const db = createSupabaseAdminClient() ?? (await createSupabaseServerClient())!;
  const url = new URL(request.url);
  const { month, daysInMonth } = getMonthDateRange(url.searchParams.get('month'));

  const syncResult = await syncMonthlySalarySlipsForSchool({
    db,
    schoolId: context.school.id,
    payrollMonth: month,
    forceRecalculateUnpaid: true,
  });

  const [{ data: slipRows, error: slipErr }, { data: staffRows, error: staffErr }] = await Promise.all([
    db
      .from('salary_slips')
      .select('*')
      .eq('school_id', context.school.id)
      .eq('payroll_month', month)
      .order('created_at', { ascending: false }),
    db
      .from('teachers')
      .select('id, employee_code, full_name, designation, department, salary_pkr, bank_name, bank_account_number, status, user_id')
      .eq('school_id', context.school.id)
      .order('employee_code'),
  ]);

  if (slipErr || staffErr) {
    return NextResponse.json(
      { error: slipErr?.message || staffErr?.message || 'Unable to load payroll records.' },
      { status: 400 }
    );
  }

  const staffMap = new Map((staffRows ?? []).map((t) => [t.id, t]));

  const slips = (slipRows ?? []).map((row) => {
    const st = staffMap.get(row.teacher_id);
    const att = syncResult.attendanceByTeacher.get(row.teacher_id) ?? {
      presentDays: 0,
      absentDays: Number(row.absent_days || 0),
      lateDays: 0,
      leaveDays: 0,
      markedDays: Number(row.absent_days || 0),
    };
    const baseSalary = Number(row.base_salary || 0);
    const perDayRate = daysInMonth > 0 ? Math.round(baseSalary / daysInMonth) : Math.round(baseSalary / 30);

    return {
      ...row,
      employeeName: st?.full_name || 'Staff Member',
      employeeCode: st?.employee_code || '',
      designation: st?.designation || 'Teacher',
      department: st?.department || 'Academics',
      bank_name: st?.bank_name || null,
      bank_account_number: st?.bank_account_number || null,
      present_days: att.presentDays,
      absent_days: Number(row.absent_days ?? att.absentDays),
      late_days: att.lateDays,
      leave_days: att.leaveDays,
      marked_days: att.markedDays,
      days_in_month: daysInMonth,
      per_day_rate: perDayRate,
    };
  });

  let totalBaseSalary = 0;
  let totalAttendanceDeduction = 0;
  let totalNetPayable = 0;
  let totalPaidAmount = 0;
  let totalUnpaidAmount = 0;
  let paidCount = 0;
  let unpaidCount = 0;

  for (const s of slips) {
    const net = Number(s.net_salary || 0);
    totalBaseSalary += Number(s.base_salary || 0);
    totalAttendanceDeduction += Number(s.attendance_deduction || 0);
    totalNetPayable += net;
    if (s.status === 'Paid') {
      paidCount += 1;
      totalPaidAmount += net;
    } else {
      unpaidCount += 1;
      totalUnpaidAmount += net;
    }
  }

  return NextResponse.json({
    month,
    daysInMonth,
    autoGeneratedCount: syncResult.createdCount,
    autoUpdatedCount: syncResult.updatedCount,
    slips,
    staff: (staffRows ?? []).filter((t) => String(t.status || '').toLowerCase() === 'active'),
    summary: {
      totalStaff: slips.length,
      totalBaseSalary,
      totalAttendanceDeduction,
      totalNetPayable,
      totalPaidAmount,
      totalUnpaidAmount,
      paidCount,
      unpaidCount,
    },
  });
}

export async function POST(request: Request) {
  const authResult = await getSchoolContext();
  if (authResult.status !== 'ok') {
    return NextResponse.json({ error: 'Unauthorized or unapproved school.' }, { status: 403 });
  }

  const { context } = authResult;
  if (!hasModulePermission(context.member, 'payroll')) {
    return NextResponse.json({ error: 'Insufficient module permissions for Payroll.' }, { status: 403 });
  }

  try {
    const body = await request.json();
    const parsed = PostActionSchema.safeParse(body);
    if (!parsed.success) {
      return NextResponse.json(
        { error: 'Invalid payroll payload.', issues: parsed.error.flatten() },
        { status: 400 }
      );
    }

    const db = createSupabaseAdminClient() ?? (await createSupabaseServerClient())!;

    if (parsed.data.action === 'generate_month') {
      const result = await syncMonthlySalarySlipsForSchool({
        db,
        schoolId: context.school.id,
        payrollMonth: parsed.data.payroll_month,
        forceRecalculateUnpaid: true,
      });

      return NextResponse.json({
        success: true,
        month: result.month,
        createdCount: result.createdCount,
        updatedCount: result.updatedCount,
      });
    }

    const input = parsed.data;
    const { data: teacher, error: tErr } = await db
      .from('teachers')
      .select('id, salary_pkr, full_name')
      .eq('id', input.teacher_id)
      .eq('school_id', context.school.id)
      .maybeSingle();

    if (tErr || !teacher) {
      return NextResponse.json({ error: 'Staff member not found.' }, { status: 404 });
    }

    const { daysInMonth, attendanceByTeacher } = await getTeacherAttendanceMapForMonth(
      db,
      context.school.id,
      input.payroll_month,
      [teacher.id]
    );

    const stats = attendanceByTeacher.get(teacher.id);
    const absentDays = stats?.absentDays ?? 0;
    const baseSalary = Number(teacher.salary_pkr || 0);
    const perDayRate = daysInMonth > 0 ? baseSalary / daysInMonth : baseSalary / 30;
    const attendanceDeduction = Math.round(perDayRate * absentDays);
    const netSalary = Math.max(
      0,
      Math.round(
        baseSalary +
          input.allowances +
          input.bonuses -
          input.deductions -
          input.advance_salary -
          attendanceDeduction
      )
    );

    const { data: existingSlip } = await db
      .from('salary_slips')
      .select('id, status')
      .eq('school_id', context.school.id)
      .eq('teacher_id', teacher.id)
      .eq('payroll_month', input.payroll_month)
      .maybeSingle();

    if (existingSlip?.status === 'Paid') {
      return NextResponse.json(
        { error: 'This salary slip is already marked Paid. Mark Unpaid first to edit.' },
        { status: 400 }
      );
    }

    const { data: savedSlip, error: saveErr } = await db
      .from('salary_slips')
      .upsert(
        {
          school_id: context.school.id,
          teacher_id: teacher.id,
          payroll_month: input.payroll_month,
          base_salary: baseSalary,
          allowances: input.allowances,
          bonuses: input.bonuses,
          deductions: input.deductions,
          advance_salary: input.advance_salary,
          absent_days: absentDays,
          attendance_deduction: attendanceDeduction,
          net_salary: netSalary,
          status: 'Unpaid',
        },
        { onConflict: 'school_id,teacher_id,payroll_month' }
      )
      .select('*')
      .single();

    if (saveErr || !savedSlip) {
      return NextResponse.json(
        { error: saveErr?.message || 'Unable to save salary slip.' },
        { status: 400 }
      );
    }

    return NextResponse.json({ success: true, slip: savedSlip });
  } catch (err) {
    return NextResponse.json(
      { error: err instanceof Error ? err.message : 'Unable to process payroll request.' },
      { status: 500 }
    );
  }
}

export async function PATCH(request: Request) {
  const authResult = await getSchoolContext();
  if (authResult.status !== 'ok') {
    return NextResponse.json({ error: 'Unauthorized or unapproved school.' }, { status: 403 });
  }

  const { context } = authResult;
  if (!hasModulePermission(context.member, 'payroll')) {
    return NextResponse.json({ error: 'Insufficient module permissions for Payroll.' }, { status: 403 });
  }

  try {
    const body = await request.json();
    const parsed = PatchActionSchema.safeParse(body);
    if (!parsed.success) {
      return NextResponse.json({ error: 'Invalid payroll update payload.' }, { status: 400 });
    }

    const db = createSupabaseAdminClient() ?? (await createSupabaseServerClient())!;
    await ensurePublicUserProfile(db, context.userId, context.userEmail, context.member.full_name);

    if (parsed.data.action === 'pay_all_unpaid') {
      const nowIso = new Date().toISOString();
      const { data: updated, error } = await db
        .from('salary_slips')
        .update({
          status: 'Paid',
          payment_method: parsed.data.payment_method,
          paid_at: nowIso,
        })
        .eq('school_id', context.school.id)
        .eq('payroll_month', parsed.data.payroll_month)
        .eq('status', 'Unpaid')
        .select('id');

      if (error) {
        return NextResponse.json({ error: error.message }, { status: 400 });
      }

      return NextResponse.json({ success: true, paidCount: updated?.length ?? 0 });
    }

    const { data: existingSlip, error: lookupErr } = await db
      .from('salary_slips')
      .select('*')
      .eq('id', parsed.data.slip_id)
      .eq('school_id', context.school.id)
      .maybeSingle();

    if (lookupErr || !existingSlip) {
      return NextResponse.json({ error: 'Salary slip not found.' }, { status: 404 });
    }

    if (parsed.data.action === 'mark_paid') {
      const { data: updatedSlip, error: updErr } = await db
        .from('salary_slips')
        .update({
          status: 'Paid',
          payment_method: parsed.data.payment_method,
          paid_at: new Date().toISOString(),
        })
        .eq('id', existingSlip.id)
        .eq('school_id', context.school.id)
        .select('*')
        .single();

      if (updErr) {
        return NextResponse.json({ error: updErr.message }, { status: 400 });
      }

      const { data: teacher } = await db
        .from('teachers')
        .select('full_name, user_id, email')
        .eq('id', existingSlip.teacher_id)
        .maybeSingle();

      if (teacher?.user_id) {
        await ensurePublicUserProfile(db, teacher.user_id, teacher.email, teacher.full_name);
        await db.from('notifications').insert({
          school_id: context.school.id,
          recipient_user_id: teacher.user_id,
          target_audience: 'Teachers',
          category: 'payroll',
          title: `Salary Paid — ${existingSlip.payroll_month}`,
          body: `Your monthly salary slip of PKR ${Number(existingSlip.net_salary).toLocaleString()} for ${existingSlip.payroll_month} has been paid via ${parsed.data.payment_method}.`,
          is_read: false,
        });
      }

      return NextResponse.json({ success: true, slip: updatedSlip });
    }

    const { data: revertedSlip, error: revErr } = await db
      .from('salary_slips')
      .update({
        status: 'Unpaid',
        payment_method: null,
        paid_at: null,
      })
      .eq('id', existingSlip.id)
      .eq('school_id', context.school.id)
      .select('*')
      .single();

    if (revErr) {
      return NextResponse.json({ error: revErr.message }, { status: 400 });
    }

    await syncMonthlySalarySlipsForSchool({
      db,
      schoolId: context.school.id,
      payrollMonth: existingSlip.payroll_month,
      teacherIds: [existingSlip.teacher_id],
      forceRecalculateUnpaid: true,
    });

    return NextResponse.json({ success: true, slip: revertedSlip });
  } catch (err) {
    return NextResponse.json(
      { error: err instanceof Error ? err.message : 'Unable to update salary slip.' },
      { status: 500 }
    );
  }
}
